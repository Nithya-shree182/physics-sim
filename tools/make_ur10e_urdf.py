#!/usr/bin/env python3
"""Generate assets/ur10e/ur10e.urdf from Universal Robots' own published parameters.

Why generate rather than hand-author: every number in the URDF must be traceable to a source, the
same rule the rest of this repository follows. The inputs are the three YAML files that Universal
Robots ships in `Universal_Robots_ROS2_Description` (branch `rolling`, `config/ur10e/`):

    default_kinematics.yaml   link offsets (the calibrated nominal set, hash calib_5119701370761913513)
    joint_limits.yaml         position, velocity and effort limits, cited to the UR10e user manual
    physical_parameters.yaml  link masses, centres of mass and FULL 3x3 inertia tensors

The link/joint structure reproduces `urdf/ur_macro.xacro` from the same commit: base_link ->
base_link_inertia (fixed, yaw pi) -> 6 revolute joints -> wrist_3_link, then the two ROS-Industrial
convention frames `flange` (rpy 0, -pi/2, -pi/2) and `tool0` (rpy pi/2, 0, pi/2).

What is deliberately NOT copied: visual meshes. The simulator takes its appearance from the Isaac
Sim USD asset; this URDF exists so Pinocchio and the plant authoring can agree on the dynamics, so
it carries inertials plus simple cylinder collisions and nothing else.

    tools/make_ur10e_urdf.py [--config DIR] [--out assets/ur10e/ur10e.urdf]

With no --config it downloads the YAML files; point --config at a directory to work offline.
"""
from __future__ import annotations

import argparse
import math
import sys
import urllib.request
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
RAW = "https://raw.githubusercontent.com/UniversalRobots/Universal_Robots_ROS2_Description/rolling/config/ur10e"
FILES = ("default_kinematics.yaml", "joint_limits.yaml", "physical_parameters.yaml")
SOURCE_NOTE = "Universal_Robots_ROS2_Description @ rolling, config/ur10e + urdf/ur_macro.xacro"

# joint name -> (kinematics key, inertial key, parent link, child link)
CHAIN = [
    ("shoulder_pan_joint", "shoulder", "shoulder", "base_link_inertia", "shoulder_link"),
    ("shoulder_lift_joint", "upper_arm", "upper_arm", "shoulder_link", "upper_arm_link"),
    ("elbow_joint", "forearm", "forearm", "upper_arm_link", "forearm_link"),
    ("wrist_1_joint", "wrist_1", "wrist_1", "forearm_link", "wrist_1_link"),
    ("wrist_2_joint", "wrist_2", "wrist_2", "wrist_1_link", "wrist_2_link"),
    ("wrist_3_joint", "wrist_3", "wrist_3", "wrist_2_link", "wrist_3_link"),
]
# rough capsule collisions, so the URDF is usable on its own; they do not affect the dynamics
COLLISION = {"shoulder_link": (0.075, 0.18), "upper_arm_link": (0.065, 0.62), "forearm_link": (0.055, 0.58),
             "wrist_1_link": (0.045, 0.12), "wrist_2_link": (0.045, 0.12), "wrist_3_link": (0.040, 0.09)}


class _DegLoader(yaml.SafeLoader):
    """joint_limits.yaml writes angles as `!degrees 360.0`."""


_DegLoader.add_constructor("!degrees", lambda ldr, node: math.radians(float(ldr.construct_scalar(node))))
_DegLoader.add_constructor("!radians", lambda ldr, node: float(ldr.construct_scalar(node)))


def load_configs(cfg_dir: Path | None) -> dict:
    out = {}
    for name in FILES:
        if cfg_dir:
            text = (cfg_dir / name).read_text()
        else:
            with urllib.request.urlopen(f"{RAW}/{name}", timeout=60) as r:   # noqa: S310 - fixed https URL
                text = r.read().decode()
        out[name.removesuffix(".yaml")] = yaml.load(text, Loader=_DegLoader)
    return out


def _n(x: float) -> str:
    """Numbers short enough to read, exact enough to round-trip."""
    return f"{float(x):.12g}"


def _xyz(d, keys=("x", "y", "z")) -> str:
    return " ".join(_n(d[k]) for k in keys)


def _rpy(d, keys=("roll", "pitch", "yaw")) -> str:
    return " ".join(_n(d.get(k, 0.0)) for k in keys)


def build(cfg: dict) -> str:
    kin = cfg["default_kinematics"]["kinematics"]
    lim = cfg["joint_limits"]["joint_limits"]
    phys = cfg["physical_parameters"]["inertia_parameters"]
    cog, rot, ten = phys["center_of_mass"], phys["rotation"], phys["tensor"]

    L: list[str] = [
        '<?xml version="1.0"?>',
        "<!-- GENERATED by tools/make_ur10e_urdf.py - do not edit by hand.",
        f"     Parameters: {SOURCE_NOTE}",
        f"     Kinematics hash: {kin.get('hash', 'unknown')}",
        "     Inertials are the manufacturer's full 3x3 tensors; visuals are deliberately absent",
        "     (the simulator uses the Isaac Sim USD asset for appearance). -->",
        '<robot name="ur10e">',
        '  <link name="base_link"/>',
    ]

    # base_link_inertia: the xacro gives it a cylinder inertia and a yaw of pi from base_link.
    bm, br, bl = phys["base_mass"], phys["links"]["base"]["radius"], phys["links"]["base"]["length"]
    b_ixx = 0.0833333 * bm * (3 * br * br + bl * bl)
    L += [
        '  <link name="base_link_inertia">',
        "    <inertial>",
        f'      <mass value="{_n(bm)}"/>',
        '      <origin xyz="0 0 0" rpy="0 0 0"/>',
        f'      <inertia ixx="{_n(b_ixx)}" ixy="0" ixz="0" iyy="{_n(b_ixx)}" iyz="0" izz="{_n(0.5 * bm * br * br)}"/>',
        "    </inertial>",
        "    <collision>",
        f'      <origin xyz="0 0 {_n(bl / 2)}" rpy="0 0 0"/>',
        f'      <geometry><cylinder radius="{_n(br)}" length="{_n(bl)}"/></geometry>',
        "    </collision>",
        "  </link>",
        '  <joint name="base_link-base_link_inertia" type="fixed">',
        '    <parent link="base_link"/>',
        '    <child link="base_link_inertia"/>',
        f'    <origin xyz="0 0 0" rpy="0 0 {_n(math.pi)}"/>',
        "  </joint>",
    ]

    for jname, kkey, ikey, parent, child in CHAIN:
        m = phys[f"{ikey}_mass"]
        c, r, t = cog[f"{ikey}_cog"], rot[ikey], ten[ikey]
        L += [
            f'  <link name="{child}">',
            "    <inertial>",
            f'      <mass value="{_n(m)}"/>',
            f'      <origin xyz="{_xyz(c)}" rpy="{_rpy(r)}"/>',
            f'      <inertia ixx="{_n(t["ixx"])}" ixy="{_n(t["ixy"])}" ixz="{_n(t["ixz"])}"'
            f' iyy="{_n(t["iyy"])}" iyz="{_n(t["iyz"])}" izz="{_n(t["izz"])}"/>',
            "    </inertial>",
        ]
        if child in COLLISION:
            rad, length = COLLISION[child]
            L += ["    <collision>",
                  f'      <origin xyz="{_xyz(c)}" rpy="{_rpy(r)}"/>',
                  f'      <geometry><cylinder radius="{_n(rad)}" length="{_n(length)}"/></geometry>',
                  "    </collision>"]
        L.append("  </link>")

        jl = lim[jname]
        L += [
            f'  <joint name="{jname}" type="revolute">',
            f'    <parent link="{parent}"/>',
            f'    <child link="{child}"/>',
            f'    <origin xyz="{_xyz(kin[kkey])}" rpy="{_rpy(kin[kkey])}"/>',
            '    <axis xyz="0 0 1"/>',
            f'    <limit lower="{_n(jl["min_position"])}" upper="{_n(jl["max_position"])}"'
            f' effort="{_n(jl["max_effort"])}" velocity="{_n(jl["max_velocity"])}"/>',
            "  </joint>",
        ]

    # ROS-Industrial convention frames, copied from ur_macro.xacro
    L += [
        '  <link name="flange"/>',
        '  <joint name="wrist_3-flange" type="fixed">',
        '    <parent link="wrist_3_link"/>',
        '    <child link="flange"/>',
        f'    <origin xyz="0 0 0" rpy="0 {_n(-math.pi / 2)} {_n(-math.pi / 2)}"/>',
        "  </joint>",
        '  <link name="tool0"/>',
        '  <joint name="flange-tool0" type="fixed">',
        '    <parent link="flange"/>',
        '    <child link="tool0"/>',
        f'    <origin xyz="0 0 0" rpy="{_n(math.pi / 2)} 0 {_n(math.pi / 2)}"/>',
        "  </joint>",
        "</robot>",
        "",
    ]
    return "\n".join(L)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--config", type=Path, default=None, help="directory holding the three UR YAML files (default: download)")
    p.add_argument("--out", type=Path, default=REPO / "assets" / "ur10e" / "ur10e.urdf")
    a = p.parse_args(argv)

    cfg = load_configs(a.config)
    urdf = build(cfg)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(urdf)

    phys = cfg["physical_parameters"]["inertia_parameters"]
    total = phys["base_mass"] + sum(phys[f"{k}_mass"] for _, _, k, _, _ in CHAIN)
    print(f"wrote {a.out} ({len(urdf.splitlines())} lines)")
    print(f"total mass {total:.3f} kg (UR10e datasheet: 33.5 kg)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
